namespace ArchForge.Analysis.Core;

// Ось usage-графа: одно МЕСТО конструирования типа (new) в коде таргета. В отличие от связей уровня
// объявлений (A использует B), это факт уровня ТЕЛА МЕТОДА — «где именно и сколько раз создаётся тип».
// Нужна, например, чтобы поймать «entity→DTO собирается инлайн в N хендлеров вне мапперов» (свод-линза).
public sealed record ConstructionSite(
    string TypeName,   // какой тип конструируется (простое имя, без дженериков/квалификаторов)
    string InType,     // в каком типе написан new (для проверки «внутри маппера/проводки»)
    string InMethod,   // в каком методе/свойстве (контекст для факта; «.ctor» для конструктора)
    string Layer,      // слой места конструирования (Api/Application/…)
    string File,
    int Line);
