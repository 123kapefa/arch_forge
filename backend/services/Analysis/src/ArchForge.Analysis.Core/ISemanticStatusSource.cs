namespace ArchForge.Analysis.Core;

// Порт: получилась ли семантика при разборе типов сервиса. false — всё посчитано семантикой (или статус неизвестен);
// true — семантика не получилась (сбой Roslyn, пустой результат, слишком много ссылок), типы взяты синтаксическим полом:
// базы только прямые, связи из тела метода не видны → роли и покрытие занижены (adr/0008). Реализация — Roslyn.
public interface ISemanticStatusSource
{
    /// <summary>true — типы сервиса получены синтаксическим полом. Вызывать после <see cref="ITypeSource.Read"/> того же пути.</summary>
    bool IsSyntaxOnly(string root);
}
